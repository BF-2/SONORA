"""Generate TypeScript structural contracts from the runtime JSON Schema subset."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
schema=json.loads((ROOT/'packages/contracts/project.schema.json').read_text(encoding='utf-8'))
def ts(node):
    if '$ref' in node:return node['$ref'].rsplit('/',1)[-1]
    if 'const' in node:return json.dumps(node['const'])
    if 'enum' in node:return ' | '.join(json.dumps(x) for x in node['enum'])
    kind=node.get('type')
    if isinstance(kind,list):return ' | '.join(ts({'type':item}) for item in kind)
    if kind=='null':return 'null'
    if kind in ('number','integer'):return 'number'
    if kind=='string':return 'string'
    if kind=='boolean':return 'boolean'
    if kind=='array':return '('+ts(node.get('items',{}))+')[]'
    if kind=='object':
        required=set(node.get('required',[]));properties=node.get('properties',{})
        return '{ '+ '; '.join(json.dumps(k)+('' if k in required else '?')+': '+ts(v) for k,v in properties.items())+('; ' if properties else '')+'[key:string]:unknown }'
    return 'unknown'
out='// Generated by scripts/generate_contracts.py. Do not hand edit.\n'
out+='\n'.join(f'export type {name} = {ts(value)};' for name,value in schema['$defs'].items())
out+='\nexport type SonoraProject = '+ts(schema)+';\n'
(ROOT/'packages/contracts/schema.ts').write_text(out,encoding='utf-8')
print('Generated packages/contracts/schema.ts')
